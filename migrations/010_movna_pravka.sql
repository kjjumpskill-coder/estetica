-- Мовна правка текстів.
--
-- Приводом стала скарга на «перемішані мови». Основна причина виявилась зовнішньою:
-- Chrome підміняв українську сторінку машинним російським перекладом. Але при
-- розборі знайшлися й справжні русизми у власних текстах — їх і прибираємо.
--
-- REPLACE() замість переліку рядків: ті самі звороти зустрічаються в кількох
-- місцях, і точкові UPDATE довелося б синхронізувати вручну.

-- «задача» у значенні «те, що треба зробити» — це російське слововживання.
-- Українською задача буває математична, а тут ідеться про завдання.
-- Зачіпає і цитату майстра, і відповідь у FAQ.
UPDATE settings SET `value` = REPLACE(`value`, 'моя задача', 'моє завдання');
UPDATE faq SET answer = REPLACE(answer, 'Моя задача', 'Моє завдання');

-- «домовитись на березі» — калька з російської ідіоми, українською так не кажуть.
UPDATE faq SET answer = REPLACE(answer, 'про це домовляємось на березі', 'про це домовляємось заздалегідь');

-- «ні в якому разі» → «в жодному разі».
UPDATE faq SET answer = REPLACE(answer, 'ні в якому разі', 'в жодному разі');
UPDATE posts SET body = REPLACE(body, 'ні в якому разі', 'в жодному разі');

-- Активні дієприкметники на -учий/-ючий в українській не вживаються.
UPDATE faq SET answer = REPLACE(answer, 'наростаючий біль', 'біль, що наростає');
UPDATE faq SET answer = REPLACE(answer, 'Наростаючий біль', 'Біль, що наростає');
UPDATE posts SET body = REPLACE(body, 'Наростаючий біль замість спадаючого', 'Біль, що наростає замість того, щоб спадати');

-- «строк» доречний у юридичному тексті, але про тривалість дії кажуть «термін».
UPDATE faq SET answer = REPLACE(answer, 'Точний строк', 'Точний термін');

-- «середні по індустрії» — калька керування; українською «середні для індустрії».
UPDATE faq SET answer = REPLACE(answer, 'середні по індустрії', 'середні для індустрії');

-- Чергування у/в: після голосної перед приголосною йде «в».
UPDATE faq SET answer = REPLACE(answer, 'Герпес у активній фазі', 'Герпес в активній фазі');

-- Незграбний зворот: епідерміс не буває «свіжим засмаглим».
UPDATE faq SET answer = REPLACE(
    answer,
    'Свіжий засмаглий епідерміс і пігмент погано дружать',
    'Свіжа засмага і пігмент погано дружать'
);

-- «без ефекту намальованості» — штучний іменник.
UPDATE services SET short_desc = REPLACE(
    short_desc,
    'Рівний контур без ефекту намальованості',
    'Рівний контур, без відчуття намальованих губ'
);

-- Відгуки. Тексти перенабрані мною з листувань, тож правлю власний переклад,
-- а не слова клієнток: зміст лишається той самий.
UPDATE reviews SET body = REPLACE(body, 'Багато хто з боку казав', 'Багато хто казав');
UPDATE reviews SET body = REPLACE(body, 'Перший раз у житті пишу відгук', 'Уперше в житті пишу відгук');
